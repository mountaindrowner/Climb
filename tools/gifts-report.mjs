#!/usr/bin/env node
// What each gift opens, region by region, and how far each flame is from where the region leads: every region played
// with the real motor (tests/helpers/reach.mjs) with the gifts he has when he comes, then with each later gift added in
// the order he is given them. Writes docs/gifts-report.md (the numbers the Metroidvania plan, docs/metroidvania.md, is
// measured by: a gift that opens nothing behind him shows here as nothing).
//   node tools/gifts-report.mjs
import { writeFileSync } from 'node:fs';
import { graph, arrival, GIFTS, giftName, reached, goalOf, nearGoal, runback, LEVELS, loadLevel } from '../tests/helpers/reach.mjs';

const LIMIT = 40;   // seconds from the nearest flame to the keeper (or the way out) before it is called long
const said = gifts => gifts.length ? gifts.map(giftName).join(', ') : 'nothing yet';
const out = [], summary = [];
out.push('# What each gift opens', '', 'Generated by `node tools/gifts-report.mjs` from the real motor (`tests/helpers/reach.mjs`). Each region is played',
  'with the gifts he has when he first comes to it, then with each later gift added in the order he is given them.',
  '"Places" are spots he can stand on. A gift that opens nothing he has walked past shows here as nothing: that is',
  `what docs/metroidvania.md sets out to change. Runbacks are the shortest way from a flame to where the region leads, at a run; over ${LIMIT} s is marked long.`, '');

for (let N = 0; N < LEVELS.length; N++){
  const NAME = LEVELS[N].name, ARR = arrival(N), later = GIFTS.filter(g => !ARR.includes(g));
  const sets = [ARR]; for (const g of later) sets.push([...sets[sets.length - 1], g]);
  const Gs = sets.map(s => graph(N, s)), G0 = Gs[0], { W, rooms, marks } = G0;
  const roomOf = k => { const i = k % W, j = (k - i) / W; const r = rooms.find(r => i >= r.tx0 && i < r.tx1 && j >= r.ty0 && j < r.ty1); return r ? (r.title && r.title !== NAME.toUpperCase() ? r.title.toLowerCase().replace(/\b\w/g, c => c.toUpperCase()) + ': ' : '') + r.name : 'between rooms'; };
  out.push(`## ${NAME}`, '', `He comes with ${said(ARR)}: **${G0.seen.size} places**.`, '');
  const opened = [];
  for (let s = 1; s < sets.length; s++){
    const g = later[s - 1], prev = Gs[s - 1].seen, now = Gs[s].seen, fresh = [...now].filter(k => !prev.has(k));
    const by = new Map(); for (const k of fresh){ const r = roomOf(k); by.set(r, (by.get(r) || 0) + 1); }
    const newRooms = rooms.filter(r => !reached(prev, r, W) && reached(now, r, W)).map(r => r.name);
    opened.push(`${giftName(g)} +${fresh.length}`);
    out.push(`- **${giftName(g)}** opens **${fresh.length}** more place${fresh.length === 1 ? '' : 's'}${fresh.length ? ': ' + [...by].sort((a, b) => b[1] - a[1]).map(([r, n]) => `${r} ${n}`).join(', ') : ''}.${newRooms.length ? ` Rooms opened: ${newRooms.join(', ')}.` : ''}`);
  }
  if (!later.length) out.push('- Every gift is already his here.');
  // the runbacks, with what he has when he comes
  const goal = goalOf(marks), near = nearGoal(goal), what = goal.type === 'boss' ? 'the keeper' : goal.type === 'exit' ? 'the way on' : 'the way back';
  // each flame with the gifts it takes to reach it (a flame in a wing is found only after its gate)
  const flames = marks.filter(m => m.type === 'shrine').map(m => { for (const G of Gs){ const r = runback(G, m, near); if (r) return { m, r }; } return { m, r: null }; });
  const spawn = marks.find(m => m.type === 'spawn'), fromStart = runback(G0, spawn, near);
  out.push('', `Runbacks to ${what}:`);
  if (fromStart) out.push(`- from where he comes in: ${fromStart.secs.toFixed(0)} s`);
  for (const f of flames) out.push(`- from the flame in ${roomOf(f.m.y * W + f.m.x)}: ${f.r ? f.r.secs.toFixed(0) + ' s' + (f.r.secs > LIMIT ? ' (long)' : '') : 'no way found'}`);
  const best = Math.min(...flames.map(f => f.r ? f.r.secs : 1e9));
  out.push('');
  summary.push(`| ${NAME} | ${said(ARR)} | ${G0.seen.size} | ${opened.join('; ') || '(all his)'} | ${flames.length} | ${best < 1e9 ? best.toFixed(0) + ' s' + (best > LIMIT ? ' (long)' : '') : '-'} |`);
}
const head = ['## At a glance', '', '| Region | He comes with | Places | What each later gift opens | Flames | Nearest flame to ' + 'where it leads |', '|---|---|---|---|---|---|', ...summary, ''];
out.splice(7, 0, ...head);
writeFileSync(new URL('../docs/gifts-report.md', import.meta.url), out.join('\n'));
console.log(head.join('\n'));
